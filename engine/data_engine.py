"""
data_engine.py
---------------
Owns everything data-shaped: turning a raw, messy CSV into a clean SQLite
table, describing that table's schema for the LLM, and running a
forest-based anomaly scan over any result set the agent produces.

Anomaly detection note:
sklearn's RandomForestClassifier/Regressor are *supervised* models and need
labels, which raw business data never has. IsolationForest is scikit-learn's
unsupervised, forest-based outlier detector: it builds an ensemble of random
decision trees exactly like a Random Forest does, but scores each row by how
few random splits it takes to isolate it. Rows that isolate quickly are the
extreme outliers. That is the "Random Forest ... flags extreme outliers"
behavior described in the project spec, implemented with the correct
algorithm from the same family.
"""

from __future__ import annotations

import re
import sqlite3
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd
from sklearn.ensemble import IsolationForest


# --------------------------------------------------------------------------
# Cleaning + ingestion
# --------------------------------------------------------------------------

def _sanitize_column_name(name: str) -> str:
    """Turn an arbitrary CSV header into a safe SQLite identifier."""
    name = name.strip().lower()
    name = re.sub(r"[^0-9a-zA-Z_]+", "_", name)
    name = re.sub(r"_+", "_", name).strip("_")
    if not name:
        name = "column"
    if name[0].isdigit():
        name = f"col_{name}"
    return name


def _sanitize_table_name(name: str) -> str:
    base = _sanitize_column_name(Path(name).stem)
    return base or "dataset"


def clean_dataframe(df: pd.DataFrame) -> pd.DataFrame:
    """Light-touch cleaning: consistent column names, trimmed strings,
    coerced numerics, and de-duplicated rows. Deliberately conservative so
    we don't silently distort the user's data."""
    df = df.copy()
    df.columns = [_sanitize_column_name(c) for c in df.columns]

    for col in df.columns:
        if df[col].dtype == object:
            df[col] = df[col].astype(str).str.strip()
            # Try to recover numeric columns that were read as text
            # (e.g. "$1,204.50" style values are left alone; plain
            # numeric-looking strings get converted).
            coerced = pd.to_numeric(
                df[col].str.replace(",", "", regex=False), errors="coerce"
            )
            if coerced.notna().mean() > 0.9:
                df[col] = coerced

    df = df.drop_duplicates()
    df = df.replace({"nan": None, "": None, "NaT": None})
    return df


@dataclass
class DatasetInfo:
    table_name: str
    row_count: int
    columns: list[str]
    numeric_columns: list[str]
    preview: list[dict] = field(default_factory=list)


def load_csv_to_sqlite(csv_path: str, db_path: str, source_filename: str) -> DatasetInfo:
    """Read a CSV, clean it, and load it into its own SQLite table.
    Returns metadata the rest of the app needs (schema, preview rows)."""
    df = pd.read_csv(csv_path)
    df = clean_dataframe(df)

    table_name = _sanitize_table_name(source_filename)
    Path(db_path).parent.mkdir(parents=True, exist_ok=True)

    with sqlite3.connect(db_path) as conn:
        df.to_sql(table_name, conn, if_exists="replace", index=False)

    numeric_columns = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]

    return DatasetInfo(
        table_name=table_name,
        row_count=len(df),
        columns=list(df.columns),
        numeric_columns=numeric_columns,
        preview=df.head(8).to_dict(orient="records"),
    )


def describe_schema(db_path: str, table_name: str) -> str:
    """Produce a compact, LLM-friendly schema description: column names,
    types, and a couple of sample values per column."""
    with sqlite3.connect(db_path) as conn:
        df = pd.read_sql_query(f'SELECT * FROM "{table_name}" LIMIT 5', conn)

    lines = [f'Table "{table_name}" columns:']
    for col in df.columns:
        dtype = "numeric" if pd.api.types.is_numeric_dtype(df[col]) else "text"
        samples = ", ".join(str(v) for v in df[col].dropna().unique()[:3])
        lines.append(f"  - {col} ({dtype}); sample values: {samples}")
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Query execution (read-only)
# --------------------------------------------------------------------------

class UnsafeQueryError(Exception):
    pass


_ALLOWED_START = re.compile(r"^\s*(SELECT|WITH)\b", re.IGNORECASE)
_FORBIDDEN = re.compile(
    r"\b(INSERT|UPDATE|DELETE|DROP|ALTER|ATTACH|PRAGMA|REPLACE|CREATE|TRUNCATE)\b",
    re.IGNORECASE,
)


def run_readonly_query(db_path: str, sql: str, row_limit: int = 500) -> pd.DataFrame:
    """Execute a SQL string generated by the LLM, but only ever as a
    read-only SELECT. This is the guardrail between free-text-generated SQL
    and the actual database."""
    sql = sql.strip().rstrip(";")
    if not _ALLOWED_START.match(sql) or _FORBIDDEN.search(sql):
        raise UnsafeQueryError(
            "Generated query was rejected because it was not a plain read-only SELECT."
        )

    with sqlite3.connect(f"file:{db_path}?mode=ro", uri=True) as conn:
        df = pd.read_sql_query(sql, conn)

    return df.head(row_limit)


# --------------------------------------------------------------------------
# Anomaly detection
# --------------------------------------------------------------------------

def detect_anomalies(df: pd.DataFrame, contamination: float = 0.08) -> pd.DataFrame:
    """Flag statistically extreme rows using an IsolationForest ensemble.

    Returns the input dataframe with two extra columns:
      - is_anomaly: bool
      - anomaly_score: lower (more negative) = more anomalous
    Rows are only scored on their numeric columns; if there are fewer than
    2 numeric columns or fewer than 10 rows, detection is skipped and
    is_anomaly is set to False everywhere (not enough signal to trust it).
    """
    result = df.copy()
    numeric_cols = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
    numeric_df = df[numeric_cols].dropna()

    if len(numeric_cols) < 1 or len(numeric_df) < 10:
        result["is_anomaly"] = False
        result["anomaly_score"] = 0.0
        return result

    model = IsolationForest(
        n_estimators=200,
        contamination=contamination,
        random_state=42,
    )
    model.fit(numeric_df)

    predictions = model.predict(numeric_df)          # -1 = anomaly, 1 = normal
    scores = model.decision_function(numeric_df)      # lower = more anomalous

    result["is_anomaly"] = False
    result["anomaly_score"] = 0.0
    result.loc[numeric_df.index, "is_anomaly"] = predictions == -1
    result.loc[numeric_df.index, "anomaly_score"] = scores

    return result.sort_values("anomaly_score")
